int main(int argc, char **argv) try {
    uint64_t raw_corpus_bytes = 0;
    int repeats = 3;
    int window_log = 27;
    bool zlib_only = false;
    std::vector<std::string> paths;
    for (int i = 1; i < argc; ++i) {
        const std::string arg = argv[i];
        if (arg == "--raw-bytes" && i + 1 < argc) {
            raw_corpus_bytes = parse_u64(argv[++i], "--raw-bytes");
        } else if (arg == "--repeat" && i + 1 < argc) {
            repeats = parse_int(argv[++i], "--repeat");
        } else if (arg == "--window-log" && i + 1 < argc) {
            window_log = parse_int(argv[++i], "--window-log");
        } else if (arg == "--zlib-only") {
            zlib_only = true;
        } else if (arg == "--help") {
            std::printf("usage: %s --raw-bytes N [--repeat N] [--window-log N] "
                        "[--zlib-only] FILE...\n",
                        argv[0]);
            return 0;
        } else if (!arg.empty() && arg[0] == '-') {
            fail("unknown option: " + arg);
        } else {
            paths.push_back(arg);
        }
    }
    if (!raw_corpus_bytes || repeats < 1 || paths.empty()) {
        fail("--raw-bytes, a positive --repeat, and at least one FILE are required");
    }

    const auto load_begin = Clock::now();
    const Corpus corpus = load_corpus(paths);
    const double load_seconds = std::chrono::duration<double>(Clock::now() - load_begin).count();
    const Bytes expected_deflated = concatenate(corpus, false, 0, false);
    const Bytes expected_expanded = concatenate(corpus, true, 0, false);

    std::printf("CORPUS files=%zu blobs=%zu deflated=%llu inflated=%llu raw=%llu "
                "metadata=%zu load_s=%.6f zlib=%s zstd=%s\n",
                corpus.files.size(), corpus.blobs.size(),
                static_cast<unsigned long long>(corpus.deflated_bytes),
                static_cast<unsigned long long>(corpus.inflated_bytes),
                static_cast<unsigned long long>(raw_corpus_bytes), metadata_bytes(corpus),
                load_seconds, zlibVersion(), ZSTD_versionString());

    const double inflate_seconds = best_void(repeats, [&] {
        Bytes joined;
        joined.reserve(corpus.inflated_bytes);
        for (const Blob &blob : corpus.blobs) {
            const Bytes value = inflate_zlib(blob.deflated);
            joined.insert(joined.end(), value.begin(), value.end());
        }
        if (joined != expected_expanded) {
            fail("timed inflate differs");
        }
    });
    print_speed("c_inflate", inflate_seconds, corpus.deflated_bytes, raw_corpus_bytes);

    const double deflate_seconds = best_void(repeats, [&] {
        Bytes joined;
        joined.reserve(corpus.deflated_bytes);
        for (const Blob &blob : corpus.blobs) {
            const Bytes value = deflate_zlib_9(blob.inflated);
            joined.insert(joined.end(), value.begin(), value.end());
        }
        if (joined != expected_deflated) {
            fail("timed zlib regeneration differs");
        }
    });
    print_speed("f_deflate9_exact", deflate_seconds, corpus.inflated_bytes,
                raw_corpus_bytes);

    benchmark_zlib_parallel(corpus, repeats, raw_corpus_bytes);

    if (zlib_only) {
        return 0;
    }

    benchmark_libdeflate(corpus, repeats, raw_corpus_bytes);

    for (int level : {1, 3}) {
        const auto baseline = best_bytes(repeats, [&] {
            return encode_whole(corpus, false, level, window_log);
        });
        std::printf("BASELINE name=deflated_whole zstd=%d wire=%zu encode_s=%.6f\n",
                    level, baseline.second.size(), baseline.first);
        run_strategy("expanded_whole", encode_whole, corpus, level, window_log, repeats,
                     raw_corpus_bytes, expected_expanded);
        run_strategy("expanded_per_tu", encode_per_file, corpus, level, window_log, repeats,
                     raw_corpus_bytes, expected_expanded);
        run_strategy("expanded_persistent_tu_flush", encode_persistent_file_flush, corpus,
                     level, window_log, repeats, raw_corpus_bytes, expected_expanded);
        run_strategy("expanded_per_blob", encode_per_blob, corpus, level, window_log, repeats,
                     raw_corpus_bytes, expected_expanded);
    }
    return 0;
} catch (const std::exception &error) {
    std::fprintf(stderr, "compressed_blob_bench: %s\n", error.what());
    return 2;
}
